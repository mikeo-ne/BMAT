const BANNER = (n, name, note) => [
  "",
  "-- " + "=".repeat(74),
  `-- ${n}. ${name}`,
  `-- ${note}`,
  "-- " + "=".repeat(74),
  "",
].join("\n");

export function buildSetupSql(dir) {
  const parts = [
    "-- East Sound Technologies — one-shot database setup.",
    "--",
    "-- Paste this whole file into Supabase → SQL Editor → New query → Run.",
    "-- It runs migrations 0001 → 0003 in one transaction: either everything",
    "-- is created, or nothing is, so a retry is always safe.",
    "--",
    "-- Generated by: npm run setup:sql   (do not edit by hand)",
    "",
    "begin;",
  ];

  MIGRATIONS.forEach(([file, note], i) => {
    const sql = readFileSync(join(dir, "supabase", "migrations", file), "utf8").trimEnd();
    parts.push(BANNER(i + 1, file, note));
    parts.push(sql);
  });

  parts.push("", "commit;", "");
  return parts.join("\n");
}
