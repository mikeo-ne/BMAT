/**
 * Builds supabase/setup.sql — every migration concatenated into one paste for
 * the Supabase SQL Editor.
 *
 * Order matters: 0002–0005 alter tables, policies and functions created by
 * 0001.
 * The whole thing runs in a single transaction, so a failure anywhere leaves
 * the project untouched instead of half-migrated.
 */
import { readFileSync } from "node:fs";
import { join } from "node:path";

export const MIGRATIONS = [
  ["0001_rbac_schema.sql", "Core schema: organisations, profiles, roles, RLS policies"],
  ["0002_stream_ingest.sql", "Stream ingest: stations, detections, evidence bucket"],
  ["0003_dashboards_live.sql", "Dashboards: aggregates, dispute queue, playout functions"],
  ["0004_realtime.sql", "Realtime: publish detections, stations and unmatched clips"],
  ["0005_alerts.sql", "Alerts: outbox, per-person switches, first-spin/chart/dispute enqueue"],
  ["0006_public_ingest_health.sql", "Public ingest health: station count and last detection for /setup"],
  ["0007_brand_mentions.sql", "Brand mentions: tracked brands, spoken mentions, review"],
  ["0008_masters_upload.sql", "Masters: upload songs with details; artists upload their own; security fixes"],
  ["0009_public_stats_honest.sql", "Homepage counts only stations that reported recently; permission tidy"],
  ["0010_airplay_alerts.sql", "Airplay alerts: every play, daily summary, settings fix"],
  ["0011_upc_check.sql", "Upload form: warn when a UPC is already used by another artist"],
  ["0012_alert_channels.sql", "Airplay alerts on WhatsApp and SMS as well as email"],
];

const BANNER = (n, name, note) => [
  "",
  "-- " + "=".repeat(74),
  `-- ${n}. ${name}`,
  `-- ${note}`,
  "-- " + "=".repeat(74),
  "",
].join("\n");

export function buildSetupSql(dir) {
  const parts = [
    "-- East Sound Technologies — one-shot database setup.",
    "--",
    "-- Paste this whole file into Supabase → SQL Editor → New query → Run.",
    "-- It runs migrations 0001 → 0003 in one transaction: either everything",
    "-- is created, or nothing is, so a retry is always safe.",
    "--",
    "-- Generated by: npm run setup:sql   (do not edit by hand)",
    "",
    "begin;",
  ];

  MIGRATIONS.forEach(([file, note], i) => {
    const sql = readFileSync(join(dir, "supabase", "migrations", file), "utf8").trimEnd();
    parts.push(BANNER(i + 1, file, note));
    parts.push(sql);
  });

  parts.push("", "commit;", "");
  return parts.join("\n");
}
