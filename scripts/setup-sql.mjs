/**
 * Builds supabase/setup.sql — the three migrations concatenated into one
 * paste for the Supabase SQL Editor.
 *
 * Order matters: 0002 and 0003 alter tables and policies created by 0001.
 * The whole thing runs in a single transaction, so a failure anywhere leaves
 * the project untouched instead of half-migrated.
 */
import { readFileSync } from "node:fs";
import { join } from "node:path";

export const MIGRATIONS = [
  ["0001_rbac_schema.sql", "Core schema: organisations, profiles, roles, RLS policies"],
  ["0002_stream_ingest.sql", "Stream ingest: stations, detections, evidence bucket"],
  ["0003_dashboards_live.sql", "Dashboards: aggregates, dispute queue, playout functions"],
];

const BANNER = (n, name, note) => [
  "",
  "-- " + "=".repeat(74),
  `-- ${n}. ${name}`,
  `-- ${note}`,
  "-- " + "=".repeat(74),
  "",
].join("\n");

export function buildSetupSql(dir) {
  const parts = [
    "-- East Sound Technologies — one-shot database setup.",
    "--",
    "-- Paste this whole file into Supabase → SQL Editor → New query → Run.",
    "-- It runs migrations 0001 → 0003 in one transaction: either everything",
    "-- is created, or nothing is, so a retry is always safe.",
    "--",
    "-- Generated by: npm run setup:sql   (do not edit by hand)",
    "",
    "begin;",
  ];

  MIGRATIONS.forEach(([file, note], i) => {
    const sql = readFileSync(join(dir, "supabase", "migrations", file), "utf8").trimEnd();
    parts.push(BANNER(i + 1, file, note));
    parts.push(sql);
  });

  parts.push("", "commit;", "");
  return parts.join("\n");
}
